-- Recon results tables for Oracle (only if you store results in Oracle instead of SQL Server).
-- Run once as the schema owner.

CREATE TABLE RECON_SUMMARY (
    RUN_ID                 VARCHAR2(20)    NOT NULL,
    RUN_TIME               DATE            NOT NULL,
    TABLE_NAME             VARCHAR2(128)   NOT NULL,
    STATUS                 VARCHAR2(10)    NOT NULL,
    SOURCE_TABLE           VARCHAR2(300),
    TARGET_TABLE           VARCHAR2(300),
    SOURCE_ROWS            NUMBER(19),
    TARGET_ROWS            NUMBER(19),
    ROW_DIFF               NUMBER(19),
    PARTITIONS             NUMBER(10),
    PARTITIONS_MISMATCHED  NUMBER(10),
    MISSING_IN_TARGET      NUMBER(10),
    EXTRA_IN_TARGET        NUMBER(10),
    VALUE_MISMATCHES       NUMBER(10),
    MOVED_PARTITION        NUMBER(10),
    DUPLICATE_KEYS         NUMBER(10),
    ROWS_FETCHED           NUMBER(19),
    SPOT_CHECKED_BUCKETS   NUMBER(10),
    DURATION_SECONDS       NUMBER(10, 2),
    ERROR_MESSAGE          VARCHAR2(4000)
);
CREATE INDEX IX_RECON_SUMMARY ON RECON_SUMMARY (RUN_TIME, TABLE_NAME);

CREATE TABLE RECON_PARTITIONS (
    RUN_ID          VARCHAR2(20)    NOT NULL,
    RUN_TIME        DATE            NOT NULL,
    TABLE_NAME      VARCHAR2(128)   NOT NULL,
    PARTITION_KEY   VARCHAR2(200),
    SOURCE_ROWS     NUMBER(19),
    TARGET_ROWS     NUMBER(19),
    ROW_DIFF        NUMBER(19),
    STATUS          VARCHAR2(10),
    FAILED_CHECKS   VARCHAR2(4000),
    NOTE            VARCHAR2(4000)
);
CREATE INDEX IX_RECON_PARTITIONS ON RECON_PARTITIONS (RUN_ID, TABLE_NAME);

CREATE TABLE RECON_DIFFERENCES (
    RUN_ID          VARCHAR2(20)    NOT NULL,
    RUN_TIME        DATE            NOT NULL,
    TABLE_NAME      VARCHAR2(128)   NOT NULL,
    PARTITION_KEY   VARCHAR2(200),
    RECORD_KEY      VARCHAR2(500),
    ISSUE           VARCHAR2(40),
    COLUMN_NAME     VARCHAR2(128),
    SOURCE_VALUE    VARCHAR2(4000),
    TARGET_VALUE    VARCHAR2(4000)
);
CREATE INDEX IX_RECON_DIFFERENCES ON RECON_DIFFERENCES (RUN_ID, TABLE_NAME);

